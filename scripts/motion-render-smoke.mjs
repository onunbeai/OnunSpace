import assert from 'node:assert/strict';
import { createHash } from 'node:crypto';
const hash = bytes => createHash('sha256').update(bytes).digest('hex');
import { readFile, mkdir } from 'node:fs/promises';
import { createRequire } from 'node:module';
import { chromium } from 'playwright';
import { defaultScene } from '../shared/motion.ts';
import { buildSceneDocument } from '../src/features/motion/sceneDocument.ts';
import { RenderQueue } from '../server/render.ts';
const require = createRequire(import.meta.url);
const outputDir = '.figma-app/evidence/motion-render';
await mkdir(outputDir, { recursive: true });
const browser = await chromium.launch({headless:true, ...(process.env.ONUN_CHROMIUM_PATH ? {executablePath:process.env.ONUN_CHROMIUM_PATH} : {})});
try {
 const context = await browser.newContext({viewport:{width:640,height:360},deviceScaleFactor:1});
 await context.route('**/*', route=>route.abort());
 const page = await context.newPage();
 const errors=[];page.on('pageerror',error=>errors.push(error.message));
 const gsap = await readFile(require.resolve('gsap/dist/gsap.min.js'),'utf8');
 const font = 'data:font/woff2;base64,'+(await readFile('public/assets/inter-medium.woff2')).toString('base64');
 await page.setContent(buildSceneDocument(defaultScene,gsap,font));
 await page.waitForFunction(()=>window.__ONUN_MOTION__?.ready);
 await page.evaluate(()=>window.__ONUN_MOTION__.seek(0));
 assert.equal(await page.locator('#title').evaluate(element=>getComputedStyle(element).opacity),'0');
 await page.evaluate(()=>window.__ONUN_MOTION__.seek(2.8));
 const state = () => Array.from(document.querySelectorAll('.motion-layer')).map(element => ({id:element.id,style:element.getAttribute('style')}));
 const firstState = await page.evaluate(state);
 const first=await page.screenshot({path:outputDir+'/scene.png'});
 await page.evaluate(()=>window.__ONUN_MOTION__.seek(.3));
 const earlier=await page.screenshot();
 console.log('Captured comparison frames', hash(first), hash(earlier));
 assert.notEqual(hash(first),hash(earlier));
 await page.evaluate(()=>window.__ONUN_MOTION__.seek(2.8));
 const repeated = await page.screenshot({path:outputDir+'/scene-repeated.png'});
 console.log('Repeated seek', hash(repeated));
 assert.deepEqual(firstState, await page.evaluate(state));
 assert.deepEqual(errors,[]);
} finally { await browser.close(); }
const queue = new RenderQueue(outputDir);
const shortScene=structuredClone(defaultScene);shortScene.duration=.5;shortScene.layers=shortScene.layers.map(layer=>({...layer,end:.5,keyframes:layer.keyframes.map(frame=>({...frame,time:frame.time/12}))}));
console.log('Starting render');
const job=queue.enqueue(shortScene,{width:640,height:360,fps:10,quality:'draft'});
await new Promise((resolve,reject)=>{const timer=setInterval(()=>{if(['completed','failed','cancelled'].includes(job.status)){clearInterval(timer);if(job.status==='completed')resolve();else reject(new Error(job.error));}},100)});
assert.equal(job.frame,5);assert.equal(job.progress,100);assert.ok(job.bytes>1000);
console.log(JSON.stringify({deterministicSeek:true,runtimeErrors:0,render:queue.publicJob(job)}));
